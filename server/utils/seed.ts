// ---------- сотрудники ----------
function buildEmployees(): Employee[] {
  const rnd = mulberry32(20261120)
  const usedSurnames = new Set<number>()
  const result: Employee[] = []
  let id = 1

  const pick = <T>(arr: T[]) => arr[Math.floor(rnd() * arr.length)]!

  for (const node of NODES) {
    for (const position of node.staff) {
      // фамилии не повторяются, пока список не исчерпан (71 сотрудник > 64 фамилий)
      if (usedSurnames.size >= surnames.length) usedSurnames.clear()
      let si = Math.floor(rnd() * surnames.length)
      while (usedSurnames.has(si)) si = (si + 1) % surnames.length
      usedSurnames.add(si)
      const [m, f] = surnames[si]!

      const female = rnd() < 0.55
      const [first, patr] = female ? pick(femaleNames) : pick(maleNames)
      result.push({
        id: id++,
        fullName: `${female ? f : m} ${first} ${patr}`,
        position,
        departmentId: node.id
      })
    }
  }
  return result
}

// ---------- отпуска ----------
function iso(y: number, m: number, d: number) {
  return `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`
}
function addDays(date: string, days: number) {
  const dt = new Date(`${date}T00:00:00Z`)
  dt.setUTCDate(dt.getUTCDate() + days)
  return dt.toISOString().slice(0, 10)
}

type V = Omit<Vacation, 'id'>

function buildVacations(employees: Employee[]): V[] {
  const rnd = mulberry32(777)
  const out: V[] = []
  const add = (employeeId: number, start: string, days: number, status: VacationStatus = 'planned', note = '') => {
    out.push({ employeeId, startDate: start, endDate: addDays(start, days - 1), status, note })
  }

  const byDept = (depId: number) => employees.filter(e => e.departmentId === depId)

  // --- Сценарии «нарочно»: пересечения ---------------------------------
  // Отдел планирования и анализа бюджета (5 человек): 4 одновременно в июле 2026 и ещё 2027
  const o4 = byDept(4)
  add(o4[0]!.id, '2026-07-06', 14, 'approved')
  add(o4[1]!.id, '2026-07-08', 14, 'approved')
  add(o4[2]!.id, '2026-07-06', 21, 'approved')
  add(o4[3]!.id, '2026-07-13', 14, 'planned', 'Перенос по согласованию с руководителем')
  add(o4[4]!.id, '2026-09-14', 14, 'planned')
  add(o4[0]!.id, '2026-12-28', 14, 'planned', 'Переходит на 2027 год') // через границу года

  // Отдел кадров: пересечение 3 из 5 в январе 2026 и в августе
  const o8 = byDept(8)
  add(o8[0]!.id, '2026-08-03', 14, 'approved')
  add(o8[1]!.id, '2026-08-10', 14, 'approved')
  add(o8[2]!.id, '2026-08-10', 14, 'approved')
  add(o8[3]!.id, '2026-02-02', 14, 'approved')
  add(o8[4]!.id, '2026-12-21', 21, 'planned', 'Отпуск с переходом на 2027 год')

  // Отдел градостроительной документации
  const o12 = byDept(12)
  add(o12[0]!.id, '2026-06-22', 14, 'approved')
  add(o12[1]!.id, '2026-06-29', 14, 'approved')
  add(o12[2]!.id, '2026-06-29', 14, 'planned')
  add(o12[3]!.id, '2026-06-29', 7, 'planned', 'Часть отпуска')
  add(o12[3]!.id, '2026-10-12', 14, 'planned', 'Вторая часть отпуска')
  add(o12[4]!.id, '2026-05-25', 14, 'approved')

  // Бюджетное управление — одновременный уход начальника и консультанта
  const o3 = byDept(3)
  add(o3[0]!.id, '2026-07-20', 14, 'approved')
  add(o3[1]!.id, '2026-07-20', 14, 'approved')

  // Отпуск, пересекающий границу месяцев
  const o6 = byDept(6)
  add(o6[0]!.id, '2026-04-27', 14, 'approved', 'Через границу апреля и мая')
  add(o6[1]!.id, '2026-05-04', 14, 'approved')
  add(o6[2]!.id, '2026-11-23', 28, 'planned', 'Переходит на декабрь')
  add(o6[3]!.id, '2027-01-11', 14, 'planned')

  // Руководство ОФО — закреплены непосредственно за ОФО
  const heads = [2, 7, 10, 17, 20].map(d => byDept(d))
  heads.forEach((list, i) => {
    add(list[0]!.id, iso(2026, 6 + (i % 3), 1 + i * 3), 14, 'approved')
    add(list[1]!.id, iso(2026, 6 + (i % 3), 1 + i * 3), 14, 'approved') // начальник и заместитель вместе
  })
  const admin = byDept(1)
  add(admin[0]!.id, '2026-08-17', 14, 'approved')
  add(admin[0]!.id, '2026-12-21', 14, 'planned', 'Через границу года')
  add(admin[1]!.id, '2026-07-27', 14, 'approved')

  // --- Остальные: случайно, часть без отпусков -------------------------
  const already = new Set(out.map(v => v.employeeId))
  const noVacation = new Set<number>() // у них отпусков в 2026 нет
  for (const e of employees) {
    if (already.has(e.id)) continue
    const r = rnd()
    if (r < 0.2) { noVacation.add(e.id); continue }
    const parts = r < 0.55 ? 1 : r < 0.85 ? 2 : 3
    let cursor = 20 + Math.floor(rnd() * 60) // день года
    for (let p = 0; p < parts; p++) {
      const len = parts === 1 ? 14 + Math.floor(rnd() * 14) : 7 + Math.floor(rnd() * 8)
      const start = addDays('2026-01-01', cursor)
      add(e.id, start, len, rnd() < 0.6 ? 'approved' : 'planned')
      cursor += len + 40 + Math.floor(rnd() * 70)
      if (cursor > 360) break
    }
  }
  return out
}

export function buildSeed() {
  const departments: Department[] = NODES.map((n, i) => ({
    id: n.id,
    name: n.name,
    parentId: n.parent,
    sort: i
  }))
  const employees = buildEmployees()
  const vacations = buildVacations(employees).map((v, i) => ({ ...v, id: i + 1 }))
  return { departments, employees, vacations }
}
