export function dayInfo(n: number): DayInfo | undefined {
  return table.get(isoFromDayNum(n))
}

/** Нерабочий ли день по производственному календарю. */
export function isNonWorking(n: number): boolean {
  const info = dayInfo(n)
  if (info?.kind === 'holiday' || info?.kind === 'dayoff') return true
  if (info?.kind === 'workday') return false
  return isWeekend(n)
}

/** Праздничные/перенесённые выходные, не совпадающие с субботой и воскресеньем (для подсветки на графике). */
export function isExtraDayOff(n: number): boolean {
  const info = dayInfo(n)
  return (info?.kind === 'holiday' || info?.kind === 'dayoff') && !isWeekend(n)
}

export function holidaysInRange(from: number, to: number): { n: number, info: DayInfo }[] {
  const out: { n: number, info: DayInfo }[] = []
  for (let n = from; n <= to; n++) {
    const info = dayInfo(n)
    if (info) out.push({ n, info })
  }
  return out
}
